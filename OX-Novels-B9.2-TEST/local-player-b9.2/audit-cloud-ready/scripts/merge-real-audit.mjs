/** Local merge only. Makes NO Cloudflare or Drive calls, never deploys. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../../..');
const files=path.join(root,'local-player-b5','src');
const configFile=path.join(root,'local-player-b5','wrangler.jsonc');
const base=path.resolve(here,'..','src');
const name='ox-b92-catalog-control';
const id=String(process.argv[2]||'').trim();
const fail=x=>{throw Error('PREPARE BLOCKED: '+x);};
const safeRead=p=>{
  const s=fs.lstatSync(p);if(!s.isFile()||s.isSymbolicLink())fail('Unsafe file: '+path.basename(p));
  return fs.readFileSync(p);
};
const hex=b=>crypto.createHash('sha256').update(b).digest('hex');
const scripts=['b92-audit-reader.js','b92-audit-scheduler.js','b92-audit-integrity.js'];
const expected={};
// These exact hashes are for the PREVIOUS reviewed reliability merge; never overwrite unknown local customizations.
const priorHashes=JSON.parse(safeRead(path.join(path.resolve(here,'..'),'prior-hashes.json')));
if(!/^[a-f\d]{8}-[a-f\d]{4}-[a-f\d]{4}-[a-f\d]{4}-[a-f\d]{12}$/i.test(id))fail('Supply the new D1 database UUID from Cloudflare; nothing changed');
if(id==='4616c768-dd75-491e-ac56-0c394577dcd7')fail('Refusing the OX website main database');
for(const f of scripts){
  expected[f]=safeRead(path.join(base,f));
  const target=path.join(files,f);
  if(!fs.existsSync(target))fail('Missing installed module '+f);
  const digest=hex(safeRead(target));
  if(digest!==priorHashes[f]&&digest!==hex(expected[f]))fail('Unexpected changes to '+f+', no files modified');
}
const manager=path.join(files,'b9-catalog-manager.js');
const managerBefore=safeRead(manager);
const adapter=safeRead(path.join(files,'b92-generation-adapter.js')).toString();
if(!adapter.includes("from './b92-audit-scheduler.js'")||!adapter.includes('runAuditCron(controller,env)'))fail('Installed audit adapter missing');
const cfg=JSON.parse(safeRead(configFile));
if(cfg.name!=='listen'||!String(cfg.main||'').endsWith('src/index.js'))fail('Unexpected Player Worker config');
const originalDB=cfg.d1_databases||[];
if(originalDB.some(x=>x.binding==='B92_POINTER_DB'))fail('Live D1 pointer already configured. Review before adding audit.');
if(originalDB.some(x=>x.binding==='B92_AUDIT_DB'&&x.database_id!==id))fail('Different existing audit DB binding');
// Wrangler 4 may insert the newly-created D1 under an autogenerated binding in wrangler.jsonc.
// Adopt ONLY the exact newly-created database and only when no existing Worker source references that alias.
const autoBindings=originalDB.filter(x=>x.database_id===id&&x.binding!=='B92_AUDIT_DB');
if(autoBindings.length>1)fail('Multiple bindings for new audit database; inspect config manually');
if(autoBindings.length===1){
  const auto=autoBindings[0];
  if(auto.database_name!==name||!/^[$A-Z_a-z][$\w]*$/.test(String(auto.binding||'')))
    fail('Existing matching-ID binding is not the expected new audit database');
  const oldBinding=auto.binding;
  const sourceUsesBinding=(dir)=>fs.readdirSync(dir,{withFileTypes:true}).some(entry=>{
    const p=path.join(dir,entry.name);
    if(entry.isDirectory())return sourceUsesBinding(p);
    if(!entry.isFile()||!/\.(?:js|mjs|ts|jsx|tsx)$/.test(entry.name))return false;
    const s=safeRead(p).toString();
    const pat=new RegExp('\\b'+oldBinding+'\\b');
    return pat.test(s);
  });
  if(sourceUsesBinding(files))fail('New database alias is referenced by existing Player source; refusing rename');
  auto.binding='B92_AUDIT_DB';
  console.log('Wrangler-created new D1 alias safely normalized to B92_AUDIT_DB (local config only).');
}
if(!originalDB.some(x=>x.binding==='B92_AUDIT_DB'))originalDB.push({binding:'B92_AUDIT_DB',database_name:name,database_id:id});
cfg.d1_databases=originalDB;
cfg.vars={...(cfg.vars||{}),B92_AUDIT_MODE:'off',B92_AUDIT_CANARY_STORY:'a-dragon-s-revenge'};
const next=Buffer.from(JSON.stringify(cfg,null,2)+'\n');
const current=safeRead(configFile);
const anyChanges=scripts.some(f=>!safeRead(path.join(files,f)).equals(expected[f]))||!current.equals(next);
if(!anyChanges){console.log('AUDIT CANARY SOURCE/CONFIG ALREADY PREPARED. Scanning remains OFF.');process.exit(0);}
const backup=path.join(root,'local-player-b9.2','_B92_PLAYER_INTEGRATION_BACKUPS','audit-cloud-'+new Date().toISOString().replace(/[:.]/g,'-'));
fs.mkdirSync(backup,{recursive:true});
fs.writeFileSync(path.join(backup,'wrangler.jsonc'),current,{flag:'wx'});
for(const f of scripts)fs.writeFileSync(path.join(backup,f),safeRead(path.join(files,f)),{flag:'wx'});
const write=(target,buf)=>{const tmp=target+'.b92-audit-tmp';fs.writeFileSync(tmp,buf);fs.renameSync(tmp,target);};
for(const f of scripts)write(path.join(files,f),expected[f]);
write(configFile,next);
if(hex(safeRead(manager))!==hex(managerBefore))fail('Manager unexpectedly modified');
console.log('B9.2 ISOLATED AUDIT DATABASE BINDING: CONFIGURED LOCALLY');
console.log('B92_AUDIT_MODE: off; cron added: NONE');
console.log('Canary story slug: a-dragon-s-revenge');
console.log('Existing Player manager: PRESERVED');
console.log('Cloudflare/Drive access: NONE; deployment: NONE');
console.log('Local backup: '+backup);
